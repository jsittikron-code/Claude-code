# -*- coding: utf-8 -*-
"""กำหนดให้เครื่องนี้เป็น "เครื่องอัปเดตข้อมูล" — เครื่องเดียวที่กดอัปเดต MOS / Solar ได้
=====================================================================================

ทำไมต้องมีไฟล์นี้
  แดชบอร์ดรันได้หลายเครื่อง แต่การอัปเดตข้อมูลต้องทำจากเครื่องเดียว เพราะทุกเครื่องเขียน
  ไฟล์ Excel/parquet ชุดเดียวกันบน OneDrive ถ้าสองเครื่องกดอัปเดต OneDrive จะแตกไฟล์เป็น
  สำเนา conflict และข้อมูลแยกเป็นสองชุด ชื่อเครื่องอัปเดตเก็บไว้ที่
  00_ETL_Pipeline\\etl_machine.txt ในโฟลเดอร์ข้อมูล ทุกเครื่องจึงเห็นค่าเดียวกัน
  เครื่องอื่นกดไอคอนอัปเดตหรือปุ่มในแดชบอร์ด จะขึ้นข้อความแล้วไม่ทำอะไรกับข้อมูล

ใช้เมื่อไร
  วันย้ายงานอัปเดตไปเครื่องใหม่ — ดับเบิลคลิก ตั้งเครื่องนี้เป็นเครื่องอัปเดต.bat บนเครื่องใหม่
  (--yes = ไม่ถามยืนยัน สำหรับสั่งจากสคริปต์)
"""

import os
import sys
import time

import data_paths


def main() -> int:
    me, owner = data_paths.this_machine(), data_paths.etl_machine()
    path = data_paths.ETL_MACHINE_FILE
    print("=" * 60)
    print("  เครื่องอัปเดตข้อมูล (MOS / Solar)")
    print("=" * 60)
    print(f"  เครื่องนี้            : {me}")
    print(f"  เครื่องอัปเดตตอนนี้   : {owner or '(ยังไม่ได้กำหนด — ทุกเครื่องกดได้)'}")
    print(f"  ไฟล์ที่เก็บ           : {path}")
    if owner == me:
        print("\n  [ok] เครื่องนี้เป็นเครื่องอัปเดตอยู่แล้ว ไม่ต้องทำอะไร")
        return 0
    if not os.path.isdir(os.path.dirname(path)):
        print("\n  [x] ไม่พบโฟลเดอร์ 00_ETL_Pipeline — ตรวจว่า OneDrive ซิงก์โฟลเดอร์ฝ่ายครบหรือยัง")
        return 1
    if owner:
        print(f"\n  หลังเปลี่ยน เครื่อง {owner} จะกดอัปเดตไม่ได้อีก")
        print("  ก่อนเปลี่ยน ให้แน่ใจว่าเครื่องนั้นอัปเดตรอบสุดท้ายเสร็จ และ OneDrive ซิงก์ครบแล้ว")
    if "--yes" not in sys.argv:
        ans = input(f"\n  ตั้งเครื่องนี้ ({me}) เป็นเครื่องอัปเดตไหม [y/n] ").strip().lower()
        if ans not in ("y", "yes", "ใช่", "ย"):
            print("  ยกเลิก ไม่ได้เปลี่ยนอะไร")
            return 1
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"{me}\n# ตั้งเมื่อ {time.strftime('%Y-%m-%d %H:%M')} — เครื่องเดียวที่กดอัปเดต MOS/Solar ได้\n"
                "# เปลี่ยนด้วย ตั้งเครื่องนี้เป็นเครื่องอัปเดต.bat อย่าแก้มือ\n")
    print(f"\n  [ok] ตั้งแล้ว — เครื่องอัปเดตคือ {me}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
