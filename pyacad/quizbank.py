TOTAL_QUESTIONS = len(QUESTIONS)


def by_topic(topic: str) -> list[dict]:
    return [q for q in QUESTIONS if q["topic"] == topic]


def build_exam(n: int = 25, rnd=None) -> list[dict]:
    """สุ่มข้อสอบตามสัดส่วนของแต่ละหมวด (คืนรายการคำถาม)"""
    import random as _random
    rnd = rnd or _random.Random()
    picked: list[dict] = []
    for topic, weight in EXAM_WEIGHTS.items():
        pool = by_topic(topic)
        want = min(len(pool), max(1, round(n * weight)))
        picked.extend(rnd.sample(pool, want))
    # ปรับจำนวนให้ตรงตามที่ขอ
    if len(picked) > n:
        picked = rnd.sample(picked, n)
    elif len(picked) < n:
        rest = [q for q in QUESTIONS if q not in picked]
        picked.extend(rnd.sample(rest, min(n - len(picked), len(rest))))
    rnd.shuffle(picked)
    return picked
