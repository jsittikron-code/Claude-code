QUESTION_BY_ID: dict[str, dict] = {q["id"]: q for q in QUESTIONS}
ALL_QUESTION_IDS: list[str] = [q["id"] for q in QUESTIONS]


def by_domain(domain: str) -> list[dict]:
    return [q for q in QUESTIONS if q["domain"] == domain]


def by_topic() -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for q in QUESTIONS:
        out.setdefault(q["topic"], []).append(q)
    return out


def build_exam(n: int, rng) -> list[dict]:
    """สุ่มชุดข้อสอบตามสัดส่วนโดเมนของ PL-300 จริง"""
    picked: list[dict] = []
    for dom, weight in EXAM_WEIGHTS.items():
        pool = by_domain(dom)
        want = min(len(pool), max(1, round(n * weight)))
        picked += rng.sample(pool, want)
    # เติมหรือตัดให้ได้จำนวนที่ขอพอดี
    if len(picked) < n:
        rest = [q for q in QUESTIONS if q not in picked]
        picked += rng.sample(rest, min(len(rest), n - len(picked)))
    rng.shuffle(picked)
    return picked[:n]
