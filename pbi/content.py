def next_lesson(done_ids: set[str]) -> dict | None:
    """บทถัดไปที่ควรเรียน — บทแรกในลำดับหลักสูตรที่ยังไม่จบ"""
    for lesson in ALL_LESSONS:
        if lesson["id"] not in done_ids:
            return lesson
    return None


def module_progress(module: dict, done_ids: set[str]) -> tuple[int, int]:
    done = sum(1 for le in module["lessons"] if le["id"] in done_ids)
    return done, len(module["lessons"])
